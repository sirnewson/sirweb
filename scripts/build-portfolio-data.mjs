/**
 * Turns the import manifest into a typed data module the app consumes.
 *   node scripts/build-portfolio-data.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';

const manifest = JSON.parse(await readFile('scripts/imported-manifest.json', 'utf8'));

// Client display names and the docket each belongs to.
const CLIENTS = {
    'lastcall': { name: 'Lastcall Events', sector: 'Events & Nightlife' },
    'big-voice': { name: 'Big Voice Fest', sector: 'Music Festival' },
    'matatu': { name: 'Matatu', sector: 'Culture & Events' },
    'ttnt6': { name: 'TTNT 6', sector: 'Live Comedy Tour' },
    'abel-mutua': { name: 'Abel Mutua', sector: 'Personal Brand' },
    'njugush': { name: 'Njugush', sector: 'Entertainment' },
    'jinwear': { name: 'Jinwear', sector: 'Apparel' },
    'best': { name: 'BEST', sector: 'Product' },
    'ebusoma': { name: 'Ebusoma', sector: 'Education' },
    'branding-2024': { name: 'Brand Systems', sector: 'Identity' },
    'poster': { name: 'Poster Archive', sector: 'Graphic Design' },
};

const esc = (s) => String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'");

const rows = manifest.map((m) => {
    const c = CLIENTS[m.clientKey] || { name: m.client, sector: '' };
    return `    { id: '${esc(m.id)}', title: '${esc(m.title)}', client: '${esc(c.name)}', clientKey: '${esc(m.clientKey)}', sector: '${esc(c.sector)}', docket: '${esc(m.docket)}', group: '${esc(m.group)}', src: '${esc(m.src)}', w: ${m.w}, h: ${m.h} },`;
}).join('\n');

const file = `/**
 * Generated by scripts/build-portfolio-data.mjs — do not edit by hand.
 * Source images live in public/uploads and were resized + re-encoded to WebP
 * on import, so nothing here is print-resolution.
 */

export type Docket = 'events' | 'graphics' | 'branding' | 'product' | 'gallery';

export interface PortfolioItem {
    id: string;
    title: string;
    client: string;
    clientKey: string;
    sector: string;
    docket: Docket;
    group: string;
    src: string;
    w: number;
    h: number;
}

export const portfolioItems: PortfolioItem[] = [
${rows}
];

export const byDocket = (docket: Docket) => portfolioItems.filter((i) => i.docket === docket);
export const byClient = (clientKey: string) => portfolioItems.filter((i) => i.clientKey === clientKey);

export const galleryItems = byDocket('gallery');
export const eventItems = byDocket('events');
export const brandingItems = byDocket('branding');
export const ttntItems = byClient('ttnt6');

/** Distinct clients that have work in a docket, in import order. */
export const clientsInDocket = (docket: Docket) => {
    const seen = new Map<string, PortfolioItem>();
    for (const item of byDocket(docket)) {
        if (!seen.has(item.clientKey)) seen.set(item.clientKey, item);
    }
    return [...seen.values()];
};
`;

await writeFile('src/data/portfolio.ts', file);
console.log(`wrote src/data/portfolio.ts with ${manifest.length} items`);
