/** The per-edition archive for one edition. */
export const editionArtwork = (series: EventSeries, edition: EventEdition): EventAsset[] =>
    assetsForEdition(series.key, edition.assetKey);

/** The older flat archive, for series imported before editions were tracked. */
export const seriesArtwork = (series: EventSeries): PortfolioItem[] =>
    series.clientKey ? byClient(series.clientKey) : [];

/** The cover a series leads with: an override, else its first imported asset. */
export const seriesCover = (series: EventSeries): string | undefined =>
    series.poster ?? assetsForSeries(series.key)[0]?.src ?? seriesArtwork(series)[0]?.src;

/** How many editions actually have artwork on file. */
export const editionsWithArtwork = (series: EventSeries) =>
    series.editions.filter((e) => editionArtwork(series, e).length > 0).length;

export const totalEditions = eventSeries.reduce((n, s) => n + s.editions.length, 0);
