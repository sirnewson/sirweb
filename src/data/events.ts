/* ---------------------------------------------------------------
   The event docket, as a run of series rather than a pile of posters.

   Almost everything here is recurring work: the same night, the same
   festival, the same tour, coming back with a new number on it. That
   repeat is the actual story — a poster is one job, a fourth season is a
   relationship — so the page is built around series and their editions,
   and the artwork hangs off that spine.

   Two archives feed it. `assetKey` reaches the per-edition import in
   ./eventGallery (generated by scripts/import-events.mjs); `clientKey`
   reaches the older flat client import in ./portfolio, which has no
   edition breakdown.

   Dates, venues and line-ups are deliberately absent. They are not
   recorded anywhere in this repo, and inventing them would put false
   claims on a public page. Add them to `editions[].note` as they get
   confirmed.
   --------------------------------------------------------------- */

export interface EventEdition {
    /** The run marker — "SN 4", "Edition II". */
    label: string;
    /** The edition's own name, where it has one. */
    name?: string;
    /** Anything confirmed and worth showing: a year, a venue, a headline. */
    note?: string;
    /** Folder key in the per-edition archive. Absent = nothing imported yet. */
    assetKey?: string;
}

export interface EventSeries {
    key: string;
    name: string;
    /** What kind of night it is. */
    kind: string;
    blurb: string;
    /** Oldest first. The page numbers them and marks the last as latest. */
    editions: EventEdition[];
    /** Links the series to the older flat archive, which has no editions. */
    clientKey?: string;
    /** Overrides the cover. Otherwise the first imported asset is used. */
    poster?: string;
}

